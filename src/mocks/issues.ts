import type { Issue } from "@/types"

let issueSeq = 0
function nextOrder() {
  issueSeq += 1
  return issueSeq
}

/** Fills in bookkeeping fields so each issue literal below only states what varies. */
function issue(partial: Omit<Issue, "order" | "createdAt" | "updatedAt"> & {
  createdAt?: string
  updatedAt?: string
}): Issue {
  return {
    order: nextOrder(),
    createdAt: partial.createdAt ?? "2026-08-20T09:00:00.000Z",
    updatedAt: partial.updatedAt ?? "2026-08-28T15:00:00.000Z",
    ...partial,
  }
}

